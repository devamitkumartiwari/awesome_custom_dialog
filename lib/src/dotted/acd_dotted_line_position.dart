/// Which edge an [ACDDottedDecoration] draws its dashed line along, when
/// its `shape` is `ACDDottedShape.line`.
enum ACDDottedLinePosition {
  /// Top edge of the decorated box.
  top,

  /// Bottom edge of the decorated box.
  bottom,

  /// Left edge of the decorated box.
  left,

  /// Right edge of the decorated box.
  right,
}
